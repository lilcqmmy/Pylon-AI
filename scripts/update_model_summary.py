# Regenerates the model summary table in PROJECT_STATUS.md (between the model-summary markers).
# Run after any backtest that adds or changes a win-probability model:
#   .venv/Scripts/python.exe -I scripts/update_model_summary.py "<project root>"
"""Every win-probability model in the backtest archive, compared with `elo_tuned` on the same games of
validation 2010-2019 (paired Brier difference, 95% week-block bootstrap). For each model the most recent
data snapshot in which both it and `elo_tuned` were backtested is used. Status comes from STATUS below
(update it when a model is promoted, retired or added)."""

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(sys.argv[1])
sys.path.insert(0, str(ROOT / "src"))

from sfi.data.sources import nflverse as N  # noqa: E402
from sfi.evaluation.metrics import block_bootstrap_mean_ci  # noqa: E402

STATUS = {  # model: (status, what it is, reference)
    "elo_tuned": ("**primary** (frozen)", "Elo, K 20, home edge 48, regression 0.5; tuned on 2001–2019",
                  "docs/holdout_freeze.md"),
    "elo_hfa": ("challenger (live, 95%)", "Elo with learned home edge (home_k 1.0)", "docs/challenger_elo_hfa.md"),
    "elo_avail": ("challenger (live, 98.3%)", "Elo + weighted starters Out/Doubtful (ridge)", "docs/challenger_avail_qbadj.md"),
    "elo_qbadj": ("challenger (live, 98.3%)", "Elo + QB rating adjustment (875 × Δ rating)", "docs/challenger_avail_qbadj.md"),
    "elo_combo": ("challenger (live, 98.75%)", "home edge + QB adjustment + availability (QB weight 0)",
                  "docs/challenger_combo.md"),
    "elo_sched": ("validation only (not live)", "Elo + schedule context (rest, travel, primetime, division)", "—"),
    "elo_tuned_platt": ("retired as candidate (still logged live)", "Platt recalibration of elo_tuned", "—"),
    "elo_default": ("retired (superseded by elo_tuned)", "Elo, K 20, regression 0.33 (untuned)", "—"),
    "elo_qb": ("retired", "Elo + QB-change flags and rating delta (ridge)", "docs/data_sources/nflverse_availability.md"),
    "pbp_logit_epa": ("retired", "Elo + offense/defense EPA (ridge)", "—"),
    "pbp_logit_full": ("retired", "Elo + 32 play-by-play team features (ridge)", "—"),
    "home_rate": ("baseline", "historical home-win rate", "—"),
    "coin_flip": ("baseline", "0.5", "—"),
}

folder = N.latest_snapshot(ROOT / "data/raw/nflverse/schedules")
games = {g.game_id: g for g in N.load_snapshot(folder, min_season=2000, known_at_hours=5).games}
# (model, snapshot) -> {game_id: p}
by = defaultdict(dict)
order = {}
with open(ROOT / "archive/backtest_forecasts.jsonl", encoding="utf-8") as fh:
    for i, line in enumerate(fh):
        if '"data_kind":"real"' not in line:
            continue
        r = json.loads(line)
        if not 2010 <= r["season"] <= 2019 or r["model_name"] not in STATUS:
            continue
        key = (r["model_name"], r["source_snapshot_id"])
        by[key][r["game_id"]] = r["distribution"]["p_home_win"]
        order.setdefault(r["source_snapshot_id"], i)

rows = []
for model in STATUS:
    snaps = sorted({s for (m, s) in by if m == model and (("elo_tuned", s) in by)}, key=lambda s: order[s])
    if not snaps:
        continue
    snap = snaps[-1]
    a, b = by[(model, snap)], by[("elo_tuned", snap)]
    d, blk = [], []
    for gid, p in a.items():
        g = games.get(gid)
        if g is None or gid not in b or not g.is_final or g.home_outcome == 0.5:
            continue
        y = g.home_outcome
        d.append((p - y) ** 2 - (b[gid] - y) ** 2)
        blk.append(f"{g.season}-{g.week}")
    if model == "elo_tuned":
        cell = "— (reference)"
    else:
        m, lo, hi = block_bootstrap_mean_ci(d, blk, 4000)
        cell = f"{m:+.4f} [{lo:+.4f}, {hi:+.4f}]"
    status, what, ref = STATUS[model]
    rows.append(f"| `{model}` | {what} | {len(d)} | {cell} | {status} | {ref} |")

table = ["<!-- model-summary:start (generated by scripts/update_model_summary.py; do not edit by hand) -->",
         "## Model summary (win probability)", "",
         "Paired Brier difference vs `elo_tuned` on validation 2010–2019 (negative = better), 95% week-block "
         "bootstrap. Validation is a sanity check only; decisions are prospective (`docs/challenger_*.md`). "
         "Effects below ≈ 0.002 are not detectable on these games (`docs/power_analysis.md`).", "",
         "| Model | What it is | Games | Δ Brier vs elo_tuned [95% CI] | Status | Reference |",
         "|---|---|---:|---|---|---|", *rows, "",
         "Distribution models (not win probability): margin/total `scores_points_empirical` is primary (beats "
         "naive on validation and holdout, intervals calibrated); player yards `players_opp_eff` is primary "
         "(beats recent average for rushing and receiving, not passing).",
         "<!-- model-summary:end -->"]
status_path = ROOT / "PROJECT_STATUS.md"
text = status_path.read_text(encoding="utf-8")
start, end = "<!-- model-summary:start", "<!-- model-summary:end -->"
if start in text:
    i, j = text.index(start), text.index(end) + len(end)
    text = text[:i] + "\n".join(table) + text[j:]
else:
    marker = "\n## "
    k = text.index(marker)  # insert before the first section
    text = text[:k] + "\n\n" + "\n".join(table) + "\n" + text[k:]
status_path.write_text(text, encoding="utf-8")
sys.stdout.reconfigure(errors="replace")  # consoles that can't print "Δ" get "?" instead of a crash
print("\n".join(rows))
